ALTER TABLE users ADD COLUMN IF NOT EXISTS premium_until TIMESTAMPTZ;
ALTER TABLE aura_sessions ADD COLUMN IF NOT EXISTS mode TEXT NOT NULL DEFAULT 'chat' CHECK (mode IN ('chat','call'));
ALTER TABLE aura_sessions ADD COLUMN IF NOT EXISTS search_filters JSONB NOT NULL DEFAULT '{}';
CREATE TABLE IF NOT EXISTS farming_usage (
 user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 window_started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 chats INTEGER NOT NULL DEFAULT 0,
 calls INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS farming_signals (
 id BIGSERIAL PRIMARY KEY,
 session_id INTEGER NOT NULL REFERENCES aura_sessions(id) ON DELETE CASCADE,
 sender_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 payload JSONB NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS farming_signals_session ON farming_signals(session_id,id);
